"""
Design checks for the doctor-study assignments generated by the labeling GUI
"""

import sys
import tempfile
from collections import Counter
from itertools import combinations
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "labeling-gui"))

RESULTS_DIR = ROOT / "results/patient_comparison_vha"
RATERS = ["abc", "def", "ghi", "jkl", "mno", "pqr"]
STUDY_CONFIG = ROOT / "labeling-gui/study_config_vha.yaml"


def personality_gaps(task_data):
    gaps = []
    seen = {}
    for position, task_id in enumerate(task_data["order"]):
        conv_id = task_data["task_assignments"][task_id]["conv_id"]
        if conv_id in seen:
            gaps.append(position - seen[conv_id])
        seen[conv_id] = position
    return gaps


def common_block(task_data):
    return {
        (v["conv_id"], v["simulator"])
        for v in task_data["task_assignments"].values()
        if v["block"] == "common"
    }


def main():
    import assignments
    import data
    import storage

    data.init(str(RESULTS_DIR), str(ROOT / "data"))
    data.init_study_config(str(STUDY_CONFIG))
    storage.init(tempfile.mkdtemp())

    raters = RATERS
    realism = {r: assignments.get_realism_assignments(r) for r in raters}
    personality = {r: assignments.get_personality_assignments(r) for r in raters}

    cfg = data.get_task_config("realism")
    arms, cases, per_case = cfg["arms"], cfg["cases"], cfg["arms_per_case"]
    exclusive = set(cfg["exclusive_arms"])
    always = set(cfg["always_arms"])
    combos = assignments.arm_combinations(
        arms, per_case, cfg["exclusive_arms"], cfg["always_arms"]
    )
    expected_per_arm = {
        arm: len(cases) * sum(arm in c for c in combos) / len(combos) for arm in arms
    }

    for rater in raters:
        items = realism[rater]["task_assignments"].values()
        shown = {v["conv_id"]: v["arms"] for v in items}
        assert set(shown) == set(cases), (
            f"{rater}: realism cases do not match the config"
        )
        assert all(len(a) == per_case for a in shown.values()), (
            f"{rater}: a case does not show exactly {per_case} arms"
        )
        assert all(len(set(a)) == per_case for a in shown.values()), (
            f"{rater}: a case shows the same arm twice"
        )
        assert all(len(exclusive & set(a)) == 1 for a in shown.values()), (
            f"{rater}: a case does not show exactly one of {sorted(exclusive)}"
        )
        assert all(always <= set(a) for a in shown.values()), (
            f"{rater}: a case does not show every always_arm {sorted(always)}"
        )
        counts = Counter(arm for a in shown.values() for arm in a)
        assert all(abs(counts[arm] - expected_per_arm[arm]) <= 1 for arm in arms), (
            f"{rater}: arms are unbalanced ({counts}, expected {expected_per_arm})"
        )

        personality_items = personality[rater]["task_assignments"].values()
        simulators = Counter(v["simulator"] for v in personality_items)
        assert set(simulators.values()) == {1}, (
            f"{rater}: duplicated personality condition"
        )
        n_cases = len({v["conv_id"] for v in personality_items})
        assert min(personality_gaps(personality[rater])) >= n_cases, (
            f"{rater}: the two items of a personality case are shown too close together"
        )
        overlap = {v["conv_id"] for v in personality_items} & set(cases)
        assert not overlap, f"{rater}: cases {overlap} appear in both tasks"

    assert len({frozenset(common_block(personality[r])) for r in raters}) == 1, (
        "personality common block differs between raters"
    )

    positions = Counter(
        (arm, position)
        for r in raters
        for v in realism[r]["task_assignments"].values()
        for position, arm in enumerate(v["arms"])
    )
    assert len({p for _, p in positions}) == per_case, (
        "an arm never reaches some column"
    )
    for arm in cfg["always_arms"]:
        arm_positions = {p for a, p in positions if a == arm}
        assert arm_positions == set(range(per_case)), (
            f"{arm} is always shown but does not reach every column position"
        )

    shared = [
        len(
            set(realism[a]["task_assignments"][t]["arms"])
            & set(realism[b]["task_assignments"][t]["arms"])
        )
        for a, b in combinations(raters, 2)
        for t in realism[a]["order"]
    ]
    assert min(shared) >= per_case - 2, (
        "two raters share fewer arms than the design allows"
    )

    assert data.normalize_rater_id(" ABCD ") == "abcd", "rater ids are not normalized"
    assert data.normalize_rater_id("abc") is None, "short rater id accepted"
    assert data.normalize_rater_id("ab1d") == "ab1d", "digit rejected in rater id"
    assert data.normalize_rater_id("ab!d") is None, "invalid character accepted"

    window = data.get_turn_window_size()
    for case in cases:
        turns = data.take_excerpt(data.load_conversation(arms[0], case), case)
        assert len(turns) == window, f"{case}: excerpt is not {window} turns"
        assert data.get_patient_summary(case), f"{case}: no case summary"

    judgements = Counter(
        (v["conv_id"], arm)
        for r in raters
        for v in realism[r]["task_assignments"].values()
        for arm in v["arms"]
    )
    per_arm = Counter(
        arm
        for r in raters
        for v in realism[r]["task_assignments"].values()
        for arm in v["arms"]
    )
    print(f"{len(raters)} raters x {len(cases)} cases x {per_case} arms")
    print(
        f"  {sum(judgements.values())} judgements; per arm: {dict(per_arm.most_common())}"
    )
    print(
        f"  raters per (case, arm): {dict(sorted(Counter(judgements.values()).items()))}"
    )
    print(
        f"  mean arms shared by a rater pair on a case: {sum(shared) / len(shared):.2f} of {per_case}"
    )
    print(f"{len(personality[raters[0]]['order'])} personality items per rater")
    print(f"excerpt window: {window} turns")
    print("All design checks passed")


if __name__ == "__main__":
    main()
